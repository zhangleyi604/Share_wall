const WebSocket = require('ws');
const URL = 'sharewall-production.up.railway.app';
const ROOM = '__v' + Date.now();
const ws = new WebSocket('wss://' + URL + '/');
const log = [];
ws.on('open', () => { log.push('OPEN'); ws.send(JSON.stringify({ type: 'join', room: ROOM, name: 'A' })); });
ws.on('message', (m) => log.push('MSG ' + m.toString().slice(0, 140)));
ws.on('close', (c) => log.push('CLOSE ' + c));
ws.on('error', (e) => log.push('ERR ' + e.message));
ws.on('unexpected-response', (req, res) => log.push('UNEXPECTED ' + res.statusCode));
setTimeout(() => { console.log(log.join('\n')); process.exit(0); }, 5000);
